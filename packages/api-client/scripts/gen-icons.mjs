// Generates src/icon-data.generated.ts from two CC0 open icon sets, so web and mobile share one data source.
//   cryptocurrency-icons (CC0-1.0): coin marks  -> COIN_ICONS
//   simple-icons         (CC0-1.0): brand glyphs -> BRAND_GLYPHS
// Run: pnpm --filter @bandha/api-client gen:icons
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const coinDir = join(dirname(require.resolve("cryptocurrency-icons/package.json")), "svg", "color");
const si = require("simple-icons");

// Coins we ship an icon for. Seeded assets first, then popular ones likely to be added next.
const COINS = [
  "btc", "eth", "usdt", "usdc", "bnb", "xrp", "ada", "sol", "doge", "dot", "trx", "ltc", "avax", "link", "dai", "bch",
  "xlm", "atom", "etc", "uni", "matic", "shib", "ton", "sui", "near", "apt", "arb", "op", "fil", "icp", "inj", "algo",
  "xmr", "vet", "hbar", "aave", "mkr", "sand", "mana", "cro", "ftm", "grt", "ldo", "pepe", "wbtc", "steth", "busd", "tusd",
];

// Brand glyphs (24x24 single path). Indonesian banks and e-wallets are not in open sets, so they use badges instead.
const BRANDS = ["binance", "coinbase", "okx", "kucoin", "trezor", "paypal", "wise"];

// Attribute reader without regex escapes: find ' name="' and read up to the closing quote.
function attr(tag, name) {
  const needle = ` ${name}="`;
  const at = tag.indexOf(needle);
  if (at < 0) return undefined;
  const start = at + needle.length;
  return tag.slice(start, tag.indexOf('"', start));
}

// Splits markup into [tagName, attributes] pairs.
function elements(markup) {
  const out = [];
  let i = 0;
  while ((i = markup.indexOf("<", i)) >= 0) {
    const end = markup.indexOf(">", i);
    let body = markup.slice(i + 1, end);
    i = end + 1;
    if (body.startsWith("/")) continue;
    if (body.endsWith("/")) body = body.slice(0, -1);
    const sp = body.search(/[ \n\t]/);
    out.push([sp < 0 ? body : body.slice(0, sp), sp < 0 ? "" : " " + body.slice(sp + 1).split(/[\n\t]+/).join(" ")]);
  }
  return out;
}

const coins = {};
const skipped = [];
for (const sym of COINS) {
  const file = join(coinDir, `${sym}.svg`);
  if (!existsSync(file)) { skipped.push(`${sym}(missing)`); continue; }
  const svg = readFileSync(file, "utf8");
  const inner = svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>"));
  const els = elements(inner).filter(([tag]) => tag !== "g" && tag !== "defs");
  const circle = els.find(([tag]) => tag === "circle");
  const paths = els.filter(([tag]) => tag === "path");
  // Only accept one <circle> plus <path>s. Anything fancier (gradients, rects, transforms) falls back to a monogram.
  const unsupported = ["transform", "gradient", "clip", "mask", "filter"].some((w) => inner.includes(w));
  if (!circle || els.length !== 1 + paths.length || unsupported || paths.length === 0) { skipped.push(`${sym}(complex)`); continue; }
  const bg = attr(circle[1], "fill");
  if (!bg || bg.startsWith("url")) { skipped.push(`${sym}(bg)`); continue; }
  coins[sym.toUpperCase()] = {
    bg,
    paths: paths.map(([, a]) => {
      const o = { d: attr(a, "d") };
      const f = attr(a, "fill");
      if (f && !["#FFF", "#FFFFFF", "#fff", "#ffffff"].includes(f)) o.fill = f;
      if (attr(a, "fill-rule") === "evenodd") o.evenodd = true;
      const op = attr(a, "fill-opacity") ?? attr(a, "opacity");
      if (op) o.opacity = Number(op);
      return o;
    }),
  };
}

const glyphs = {};
for (const slug of BRANDS) {
  const icon = Object.values(si).find((i) => i && i.slug === slug);
  if (icon) glyphs[slug] = { path: icon.path, hex: `#${icon.hex}` };
  else skipped.push(`${slug}(brand missing)`);
}

const out = `// GENERATED by scripts/gen-icons.mjs from CC0 icon sets (cryptocurrency-icons, simple-icons). Do not edit by hand.
export interface CoinPath { d: string; fill?: string; evenodd?: boolean; opacity?: number }
export interface CoinIcon { bg: string; paths: CoinPath[] }
export const COIN_ICONS: Record<string, CoinIcon> = ${JSON.stringify(coins)};
export const BRAND_GLYPHS: Record<string, { path: string; hex: string }> = ${JSON.stringify(glyphs)};
`;
writeFileSync(join(here, "..", "src", "icon-data.generated.ts"), out);
console.log(`coins: ${Object.keys(coins).length}  brand glyphs: ${Object.keys(glyphs).length}  skipped: ${skipped.join(", ") || "none"}`);
console.log(`bytes: ${out.length}`);
